func TestAnIndexRendered(t *testing.T) {
	now := people()
	now.Indexes = []model.Index{{
		Name: "people_lower", Unique: true, Method: "btree",
		Columns:   []model.IndexColumn{{Expression: "lower(name)"}, {Name: "note", Descending: true}},
		Include:   []string{"id"},
		Predicate: "note IS NOT NULL",
	}}
	got := altered(t, people(), now)
	want := `CREATE UNIQUE INDEX "people_lower" ON "public"."people" USING btree (lower(name), "note" DESC) ` +
		`INCLUDE ("id") WHERE note IS NOT NULL`
	if len(got) != 1 || got[0] != want {
		t.Errorf("it rendered\n\t%s\nwant\n\t%s", strings.Join(got, "\n\t"), want)
	}
}

// A name with a quote in it is quoted, and a comment with an apostrophe is
// doubled: both are places a person's words reach a statement.
func TestNamesAndWordsAreQuoted(t *testing.T) {
	ref := model.NewRef(model.KindTable, "db", "public", "people")
	got := renamedSQL(t, ref, "note", `od"d`)
	if len(got) != 1 || !strings.Contains(got[0], `RENAME COLUMN "note" TO "od""d"`) {
		t.Errorf("the rename reads %v", got)
	}

	now := people()
	now.Columns[2].Comment = "it's theirs"
	comment := altered(t, people(), now)
	if len(comment) != 1 || !strings.Contains(comment[0], `IS 'it''s theirs'`) {
		t.Errorf("the comment reads %v", comment)
	}
}

func TestDroppingAnObject(t *testing.T) {
	ref := model.NewRef(model.KindTable, "db", "public", "people")
	got := droppedSQL(t, ref, false)
	if len(got) != 1 || got[0] != `DROP TABLE "public"."people"` {
		t.Errorf("it rendered %v", got)
	}
	got = droppedSQL(t, ref, true)
	if got[0] != `DROP TABLE "public"."people" CASCADE` {
		t.Errorf("cascading rendered %v", got)
	}
	view := model.NewRef(model.KindView, "db", "public", "recent")
	if got := droppedSQL(t, view, false); got[0] != `DROP VIEW "public"."recent"` {
		t.Errorf("a view rendered %v", got)
	}
}

