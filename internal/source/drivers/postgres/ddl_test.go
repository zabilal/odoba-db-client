func col(name, native string, nullable bool) model.Column {
	return model.Column{Name: name, Type: model.DataType{
		Class: model.TypeString, Native: native, Nullable: nullable, Length: -1}}
}

// people is the table these render against.
func people() *model.Table {
	return &model.Table{
		Name: "people",
		Columns: []model.Column{
			{Name: "id", Type: model.DataType{Class: model.TypeInteger, Native: "integer"}, Identity: true},
			col("name", "text", false),
			col("note", "varchar(40)", true),
		},
		PrimaryKey: &model.PrimaryKey{Name: "people_pkey", Columns: []string{"id"}},
	}
}

func sqlOf(t *testing.T, stmts []source.Statement, err error) []string {
	t.Helper()
	if err != nil {
		t.Fatalf("rendering: %v", err)
	}
	out := make([]string, len(stmts))
	for i, s := range stmts {
		out[i] = s.SQL
	}
	return out
}

// altered, created and dropped render one change, so that a test reads as
// what it is asking rather than as two lines of plumbing.
// peopleRef names the fixture table the way the explorer does.
var peopleRef = model.NewRef(model.KindTable, "db", "public", "people")

func altered(t *testing.T, from, to *model.Table) []string {
	t.Helper()
	stmts, err := dialect{}.AlterObject(peopleRef, from, to)
	return sqlOf(t, stmts, err)
}

func created(t *testing.T, tbl *model.Table) []string {
	t.Helper()
	stmts, err := dialect{}.CreateObject(peopleRef, tbl)
	return sqlOf(t, stmts, err)
}

// createdObj renders any object, which is how the source kinds are asked.
func createdObj(t *testing.T, ref model.ObjectRef, obj any) []string {
	t.Helper()
	stmts, err := dialect{}.CreateObject(ref, obj)
	return sqlOf(t, stmts, err)
}

func renamedSQL(t *testing.T, ref model.ObjectRef, from, to string) []string {
	t.Helper()
	stmts, err := dialect{}.RenameColumn(ref, from, to)
	return sqlOf(t, stmts, err)
}

func droppedSQL(t *testing.T, ref model.ObjectRef, cascade bool) []string {
	t.Helper()
	stmts, err := dialect{}.DropObject(ref, cascade)
	return sqlOf(t, stmts, err)
}

func TestATableRenderedWhole(t *testing.T) {
	tbl := people()
	tbl.Comment = "who they are"
	tbl.Columns[1].Comment = "what they are called"
	tbl.Uniques = []model.UniqueConstraint{{Name: "people_name_key", Columns: []string{"name"}}}
	tbl.Checks = []model.CheckConstraint{{Name: "people_name_len", Expression: "length(name) > 0"}}
	tbl.ForeignKeys = []model.ForeignKey{{Name: "people_note_fk", Columns: []string{"note"},
		RefSchema: "public", RefTable: "notes", RefColumns: []string{"id"}, OnDelete: model.ActionCascade}}
	tbl.Indexes = []model.Index{{Name: "people_note_idx", Method: "btree",
		Columns: []model.IndexColumn{{Name: "note", Descending: true}}}}

	got := created(t, tbl)
	if len(got) != 4 {
		t.Fatalf("it rendered %d statements:\n%s", len(got), strings.Join(got, "\n"))
	}
	create := got[0]
	for _, want := range []string{
		`CREATE TABLE "public"."people"`,
		`"id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL`,
		`"name" text NOT NULL`,
		`"note" varchar(40)`,
		`CONSTRAINT "people_pkey" PRIMARY KEY ("id")`,
		`CONSTRAINT "people_name_key" UNIQUE ("name")`,
		`CONSTRAINT "people_note_fk" FOREIGN KEY ("note") REFERENCES "public"."notes" ("id") ON DELETE CASCADE`,
		`CONSTRAINT "people_name_len" CHECK (length(name) > 0)`,
	} {
		if !strings.Contains(create, want) {
			t.Errorf("the table does not say %q:\n%s", want, create)
		}
	}
	// The index is its own statement, because it is not part of the table.
	if want := `CREATE INDEX "people_note_idx" ON "public"."people" USING btree ("note" DESC)`; got[1] != want {
		t.Errorf("the index reads\n\t%s\nwant\n\t%s", got[1], want)
	}
	// And the comments come last, quoted as PostgreSQL reads them.
	if !strings.Contains(got[2], `COMMENT ON TABLE "public"."people" IS 'who they are'`) {
		t.Errorf("the table's comment reads %s", got[2])
	}
	if !strings.Contains(got[3], `COMMENT ON COLUMN "public"."people"."name" IS 'what they are called'`) {
		t.Errorf("the column's comment reads %s", got[3])
	}
}

// The order is the point: drops before the columns they hold, adds after
// them, comments last.
func TestTheOrderStatementsComeBackIn(t *testing.T) {
	was := people()
	was.Uniques = []model.UniqueConstraint{{Name: "people_note_key", Columns: []string{"note"}}}

	now := people()
	now.Columns = slices.Delete(now.Columns, 2, 3) // note goes
	now.Uniques = nil                              // and the unique on it
	now.Columns = append(now.Columns, col("email", "text", true))
	now.Columns[1].Comment = "what they are called"
	// And a constraint on the column that arrives, which cannot be made
	// until there is a column to make it on.
	now.Uniques = []model.UniqueConstraint{{Name: "people_email_key", Columns: []string{"email"}}}

	got := altered(t, was, now)
	if len(got) < 4 {
		t.Fatalf("it rendered %d statements:\n%s", len(got), strings.Join(got, "\n"))
	}
	at := func(fragment string) int {
		return slices.IndexFunc(got, func(s string) bool { return strings.Contains(s, fragment) })
	}
	dropKey, dropCol := at("DROP CONSTRAINT"), at("DROP COLUMN")
	add, addKey := at("ADD COLUMN"), at("ADD CONSTRAINT")
	comment := at("COMMENT ON COLUMN")
	for _, c := range []struct {
		what     string
		at, then int
	}{
		{"a constraint dropped before the column it holds", dropKey, dropCol},
		{"a column dropped before another is added", dropCol, add},
		{"a column added before the constraint made on it", add, addKey},
		{"everything before the comments", addKey, comment},
	} {
		if c.at < 0 || c.then < 0 {
			t.Fatalf("%s: one of them is missing from\n%s", c.what, strings.Join(got, "\n"))
		}
		if c.at > c.then {
			t.Errorf("%s: they came back as\n%s", c.what, strings.Join(got, "\n"))
		}
	}
}

// Two tables cannot say which column was renamed to which, so a column that
// went and a column that arrived render as a drop and an add. Rendering them
// as a rename would be a guess, and a wrong guess throws a column's data
// away.
func TestATableCannotGuessARename(t *testing.T) {
	now := people()
	now.Columns[2].Name = "email"

	got := altered(t, people(), now)
	if len(got) != 2 {
		t.Fatalf("it rendered %v", got)
	}
	if !strings.Contains(strings.Join(got, " "), `DROP COLUMN "note"`) {
		t.Errorf("it did not drop the old column: %v", got)
	}
	if !strings.Contains(strings.Join(got, " "), `ADD COLUMN "email"`) {
		t.Errorf("it did not add the new one: %v", got)
	}
	for _, s := range got {
		if strings.Contains(s, "RENAME") {
			t.Errorf("it guessed a rename: %s", s)
		}
	}
}

// A rename is its own statement, asked for by whoever knows one happened.
func TestARenameIsAskedForOnItsOwn(t *testing.T) {
	ref := model.NewRef(model.KindTable, "db", "public", "people")
	got := renamedSQL(t, ref, "note", "email")
	want := `ALTER TABLE "public"."people" RENAME COLUMN "note" TO "email"`
	if len(got) != 1 || got[0] != want {
		t.Errorf("it rendered\n\t%s\nwant\n\t%s", strings.Join(got, "\n\t"), want)
	}
	// A rename to the same name is no statement at all.
	if got := renamedSQL(t, ref, "note", "note"); len(got) != 0 {
		t.Errorf("renaming a column to itself rendered %v", got)
	}
	// And one with a name missing is refused rather than rendered half.
	if _, err := (dialect{}).RenameColumn(ref, "note", ""); err == nil {
		t.Error("a rename to nothing was rendered")
	}
}

func TestWhatOneColumnChangingRenders(t *testing.T) {
	for _, c := range []struct {
		what string
		to   func(*model.Column)
		want string
	}{
		{"a type", func(c *model.Column) { c.Type.Native = "text" },
			`ALTER TABLE "public"."people" ALTER COLUMN "note" TYPE text`},
		{"not null", func(c *model.Column) { c.Type.Nullable = false },
			`ALTER TABLE "public"."people" ALTER COLUMN "note" SET NOT NULL`},
		{"a default", func(c *model.Column) { c.Default, c.HasDefault = "'nobody'", true },
			`ALTER TABLE "public"."people" ALTER COLUMN "note" SET DEFAULT 'nobody'`},
		{"a comment", func(c *model.Column) { c.Comment = "what they wrote" },
			`COMMENT ON COLUMN "public"."people"."note" IS 'what they wrote'`},
	} {
		t.Run(c.what, func(t *testing.T) {
			now := people()
			c.to(&now.Columns[2])
			got := altered(t, people(), now)
			if len(got) != 1 || got[0] != c.want {
				t.Errorf("it rendered\n\t%s\nwant\n\t%s", strings.Join(got, "\n\t"), c.want)
			}
		})
	}

	// Nullable and default the other way round.
	was := people()
	was.Columns[2].Default, was.Columns[2].HasDefault = "'x'", true
	now := people()
	now.Columns[2].Type.Nullable = true
	got := altered(t, was, now)
	if len(got) != 1 || got[0] != `ALTER TABLE "public"."people" ALTER COLUMN "note" DROP DEFAULT` {
		t.Errorf("dropping a default rendered %v", got)
	}
}

// A table that says the same thing renders nothing, so a designer with no
// changes has nothing to show and nothing to run.
func TestATableThatDidNotChangeRendersNothing(t *testing.T) {
	got, err := dialect{}.AlterObject(peopleRef, people(), people())
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 0 {
		t.Errorf("it rendered %d statements: %+v", len(got), got)
	}
}

func TestRenamingTheTableComesFirstAndEverythingFollowsIt(t *testing.T) {
	now := people()
	now.Name = "humans"
	now.Columns[2].Type.Native = "text"

	got := altered(t, people(), now)
	if len(got) != 2 {
		t.Fatalf("it rendered %v", got)
	}
	if got[0] != `ALTER TABLE "public"."people" RENAME TO "humans"` {
		t.Errorf("the rename reads %s", got[0])
	}
	// What follows names the table by what it is now called, because by then
	// that is what it is called.
	if !strings.HasPrefix(got[1], `ALTER TABLE "public"."humans" `) {
		t.Errorf("what followed the rename reads %s", got[1])
	}
}

